-- OPTIONAL. Not run by the app. Converts the older "Setup context" rules to the
-- as-written form (as_written.py): category CONTEXT -> AS_WRITTEN, and their
-- NO_TRANSFORMATION action -> AS_WRITTEN, so the FDD, lineage and sample data stop
-- reading them as "copies the source unchanged".
-- As of 2026-10-15 one live rule is affected: 104857 (Location, Plant Core Stage View).
-- Co-authored with CoCo

USE ROLE ROLE_IF_CDA_PDH_SUPPLY_PLANNING_ANALYSIS_CONTRIBUTOR;

-- 1. Backups
CREATE TABLE IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE_BKP_CONTEXT_TO_AS_WRITTEN AS
SELECT * FROM IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE
WHERE UPPER(RULE_CATEGORY) = 'CONTEXT';

CREATE TABLE IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE_ACTION_BKP_CONTEXT_TO_AS_WRITTEN AS
SELECT a.* FROM IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE_ACTION a
JOIN IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE r ON r.RULE_ID = a.RULE_ID
WHERE UPPER(r.RULE_CATEGORY) = 'CONTEXT';

-- 2. Convert
BEGIN;

INSERT INTO IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE_CHANGE_HISTORY
    (CHANGE_ID, RULE_ID, CHANGE_TYPE, OLD_VALUE, NEW_VALUE, CHANGED_BY)
SELECT IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.SEQ_RULE_CHANGE_HISTORY.NEXTVAL,
       RULE_ID, 'RULE_CATEGORY', RULE_CATEGORY, 'AS_WRITTEN', CURRENT_USER()
FROM IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE
WHERE UPPER(RULE_CATEGORY) = 'CONTEXT';

UPDATE IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE_ACTION a
SET ACTION_TYPE = 'AS_WRITTEN'
FROM IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE r
WHERE r.RULE_ID = a.RULE_ID
  AND UPPER(r.RULE_CATEGORY) = 'CONTEXT'
  AND UPPER(a.ACTION_TYPE) = 'NO_TRANSFORMATION';

UPDATE IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_XFRM_BASE.RULE
SET RULE_CATEGORY = 'AS_WRITTEN', UPDATED_BY = CURRENT_USER(), UPDATED_TS = CURRENT_TIMESTAMP()
WHERE UPPER(RULE_CATEGORY) = 'CONTEXT';

COMMIT;

